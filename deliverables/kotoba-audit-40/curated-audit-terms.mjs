export function buildCuratedMap() {
  const map = {};
  const seen = new Set();
  let seq = 1;
  for (const row of CURATED_ROWS) {
    const [kanji, furigana, unitType, arti, dictForm] = row;
    if (seen.has(kanji)) {
      throw new Error(`Duplicate curated surface in CURATED_ROWS: ${kanji}`);
    }
    seen.add(kanji);
    if (!arti || arti.length > 60) {
      throw new Error(`Invalid arti length (${arti?.length}) for ${kanji}: ${arti}`);
    }
    if ((unitType === 'inflected_verb' || unitType === 'inflected_adj') && !dictForm) {
      throw new Error(`Missing dictForm for inflected entry ${kanji}`);
    }
    const id = `kb-audit-${String(seq++).padStart(4, '0')}`;
    map[kanji] = {
      id,
      kanji,
      furigana,
      unitType,
      arti,
      ...(dictForm ? { dictForm } : {}),
      status: 'verified',
    };
  }
  return map;
}
